"""Generate the independent reference fixture for AWQ slice 2's e2e correctness
test (tests/awq_qwen3_reference.rs).

This is NOT Lightbulb's own output -- it is HF transformers + autoawq,
pinned versions, run once in WSL2 (see reproduce-reference.sh) because
autoawq has no Windows wheel and its `triton` dependency has no Windows PyPI
wheel at all. The resulting JSON is committed as a fixture; the Rust-side
test and ordinary `cargo test` runs never need WSL2 or Python at all.

Usage (inside the pinned venv this script's own venv file documents):
    venv/bin/python generate_reference.py <model_dir> <out_json>
"""
import json
import platform
import subprocess
import sys

import torch
from transformers import AutoModelForCausalLM, AutoTokenizer

# Pinned to match the loader_f32.rs/generate.rs precedent elsewhere in this
# repo ("The capital of France is") rather than inventing a new prompt.
PROMPT = "The capital of France is"
MAX_NEW_TOKENS = 16

MODEL_REPO = "Orion-zhen/Qwen3-0.6B-AWQ"
MODEL_REVISION = "9f607bee5fca19cba0bd2b383ba804c89385ea18"
MODEL_LICENSE = "gpl-3.0"
BASE_MODEL_REPO = "Qwen/Qwen3-0.6B"
BASE_MODEL_LICENSE = "apache-2.0"


def pip_freeze_versions() -> dict:
    out = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True, check=True
    ).stdout
    versions = {}
    for line in out.splitlines():
        if "==" in line:
            name, _, ver = line.partition("==")
            versions[name.lower()] = ver
    return versions


def main() -> None:
    model_dir, out_path = sys.argv[1], sys.argv[2]

    tok = AutoTokenizer.from_pretrained(model_dir)
    model = AutoModelForCausalLM.from_pretrained(
        model_dir, torch_dtype=torch.float16, device_map="cuda"
    )
    model.eval()

    # add_special_tokens=True, matching this repo's own tokenizer-encode
    # precedent (src/model_fuel/loader_f32.rs's `tok.encode(.., true)`), so
    # the Rust-side comparison tokenizes identically.
    input_ids = tok(PROMPT, return_tensors="pt", add_special_tokens=True).input_ids.to("cuda")
    prompt_len = input_ids.shape[1]

    with torch.no_grad():
        out = model.generate(
            input_ids,
            max_new_tokens=MAX_NEW_TOKENS,
            do_sample=False,
            temperature=None,
            top_p=None,
            top_k=None,
        )

    generated = out[0, prompt_len:].tolist()
    pkg_versions = pip_freeze_versions()

    record = {
        "_README": (
            "Independent reference for AWQ slice 2's e2e correctness test -- generated by HF "
            "transformers + autoawq (NOT Lightbulb's own output). A mismatch against this "
            "fixture is a Lightbulb correctness signal, unlike tests/model_fuel_golden.rs's "
            "tier-3 regression net, which only checks 'did Lightbulb's own output move'. "
            "Regenerate with scripts/awq_reference/reproduce-reference.sh; see "
            "scripts/awq_reference/README.md."
        ),
        "provenance": {
            "generated_at_utc": __import__("datetime").datetime.now(
                __import__("datetime").timezone.utc
            ).isoformat(),
            "host": f"WSL2 {platform.platform()}",
            "python": platform.python_version(),
            "torch": pkg_versions.get("torch", torch.__version__),
            "transformers": pkg_versions.get("transformers", "unknown"),
            "accelerate": pkg_versions.get("accelerate", "unknown"),
            "autoawq": pkg_versions.get("autoawq", "unknown"),
            "cuda": torch.version.cuda,
            "gpu": torch.cuda.get_device_name(0) if torch.cuda.is_available() else None,
            "model_repo": MODEL_REPO,
            "model_revision": MODEL_REVISION,
            "model_license": MODEL_LICENSE,
            "base_model_repo": BASE_MODEL_REPO,
            "base_model_license": BASE_MODEL_LICENSE,
            "command": "scripts/awq_reference/reproduce-reference.sh",
        },
        "prompt": PROMPT,
        "add_special_tokens": True,
        "max_new_tokens": MAX_NEW_TOKENS,
        "prompt_token_ids": input_ids[0].tolist(),
        "generated_token_ids": generated,
        "generated_text": tok.decode(generated, skip_special_tokens=True),
    }
    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(record, f, indent=2)
        f.write("\n")
    print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
